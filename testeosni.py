def classificar_fluxo(row):

    origem = row["origem"].lower()
    destino = row["destino"].lower()

    if "aldeia" in origem and "comfrio" in destino:
        return "Aldeia → Comfrio"

    if "aldeia" in origem:
        return "Aldeia → CD"

    if "comfrio" in origem:
        return "Comfrio → CD"

    return "Outros"


